package Study_B1.Day01;

import java.util.*;

/**
 * 프로그래머스 389480. 완전범죄
 * (https://school.programmers.co.kr/learn/courses/30/lessons/389480)
 *
 * [문제 조건]
 * - A도둑, B도둑이 팀을 이뤄 물건 전부(info의 각 행 하나가 물건 하나)를 나눠서 훔친다.
 *   각 물건은 반드시 둘 중 한 명이 훔쳐야 하며, 동시에 훔칠 수는 없다(=한 명에게만 배정).
 * - 물건 i를 A가 훔치면 A흔적이 info[i][0]만큼, B가 훔치면 B흔적이 info[i][1]만큼 쌓인다.
 * - A는 누적 흔적이 n 이상이면 붙잡히고, B는 누적 흔적이 m 이상이면 붙잡힌다.
 * - 둘 다 붙잡히지 않도록 모든 물건을 훔칠 때, A의 누적 흔적 개수의 최솟값을 구하라.
 *   (불가능하면 -1)
 *
 * [핵심 아이디어 - 0/1 배낭(Knapsack) DP]
 * - 각 물건마다 "A가 훔친다 / B가 훔친다" 중 하나를 선택하는 이진 선택 문제이므로
 *   0/1 knapsack 형태의 DP로 풀 수 있다.
 * - dp[x] 의 의미: "지금까지 처리한 물건들 중 A에게 배정한 것들의 흔적 합이 정확히 x일 때,
 *   그 상태를 만드는 여러 배정 방법 중 B의 누적 흔적 합의 최솟값"
 * - x(=A의 누적 흔적)는 0부터 n-1까지만 배열로 관리한다.
 *   → A는 흔적이 n 이상이 되는 순간 붙잡히므로, x가 n 이상인 상태는 애초에 "무효한 해"이며
 *     추적할 필요가 없다(배열 크기를 n으로 잡아 자동으로 걸러낸다).
 * - dp 배열 초기화: dp[0] = 0 (아직 아무 물건도 A에게 배정하지 않았다면 A흔적은 0, B흔적도 0),
 *   나머지는 INF(도달 불가능한 상태로 표시).
 *
 * [물건 하나(a, b)를 처리할 때의 점화식]
 * - 이 물건을 B가 훔치는 경우: A누적(cur)은 그대로, B누적은 dp[cur] + b
 * - 이 물건을 A가 훔치는 경우: A누적이 cur가 되려면 이전 상태의 A누적은 (cur - a)였어야 하고,
 *   그 상태에서 B누적은 그대로(=dp[cur - a])이다.
 * - dp[cur] = min(두 경우) 로 갱신한다.
 * - cur을 n-1부터 0까지 "역순"으로 순회하는 이유: 0/1 knapsack에서 물건 하나를 여러 번
 *   중복 사용하지 않기 위한 표준 트릭이다. cur을 감소시키며 갱신하면, dp[cur]을 계산할 때
 *   참조하는 dp[cur - a](더 작은 인덱스)가 아직 "이번 물건 처리 전" 값 그대로 남아있어서
 *   같은 물건을 두 번 쓰는 것을 방지한다. (만약 오름차순으로 돌면 방금 갱신한 값을
 *   또 참조하게 되어 같은 물건을 여러 번 A에게 배정하는 것처럼 계산되는 오류가 생긴다.)
 * - a가 n보다 크면(=이 물건 하나만 A에게 줘도 바로 붙잡히는 경우) cur >= a 조건을
 *   만족하는 인덱스가 배열 범위 안에 존재하지 않으므로, 이 물건은 자동으로
 *   "A에게는 절대 배정될 수 없음" 상태로 처리된다(별도 예외처리 불필요).
 *
 * [정답 도출]
 * - 모든 물건 처리가 끝나면 dp[x]는 "A흔적 합이 정확히 x"인 모든 배정 방법 중
 *   B흔적 합의 최솟값이다.
 * - A의 흔적은 최소화하는 것이 목표이므로, x=0부터 오름차순으로 훑으면서
 *   dp[x] < m(=B도 붙잡히지 않는 조건)을 만족하는 첫 x를 찾으면 그것이 정답이다.
 * - 끝까지 찾지 못하면 어떤 배정으로도 둘 다 붙잡히지 않게 할 수 없다는 뜻이므로 -1 반환.
 *
 * [복잡도]
 * - info 길이 ≤ 40, n ≤ 120 → 시간복잡도 O(물건 수 × n) = O(40 × 120) 수준으로 매우 가볍다.
 */
public class prog_완전범죄 {

	public int solution(int[][] info, int n, int m) {
		final int INF = Integer.MAX_VALUE; // "도달 불가능한 상태"를 표시하는 무한대 값

		int[] dp = new int[n];  // dp[x] = A누적 흔적이 정확히 x일 때 가능한 B누적 흔적의 최솟값 (인덱스 0~n-1)
		Arrays.fill(dp, INF);   // 처음엔 아무 물건도 안 정했으니 전부 "도달 불가(INF)"로 초기화
		dp[0] = 0;              // 유일하게 처음부터 가능한 상태: A=0, B=0

		for (int[] item : info) {               // 물건을 하나씩 꺼내 DP에 반영 (0/1 knapsack)
			int a = item[0], b = item[1];       // a: A가 훔칠 때 흔적, b: B가 훔칠 때 흔적

			for (int cur = n - 1; cur >= 0; cur--) {
				// cur: 이 물건까지 반영한 뒤 A누적 후보값. n-1→0 역순 순회는 같은 물건 중복 사용 방지용
				// (오름차순으로 돌면 dp[cur-a]가 이미 이번 물건이 반영된 값이 되어 이중 계산됨)

				int option1 = (dp[cur] == INF ) ? INF : dp[cur] + b;
				// [B에게 배정] A누적(cur)은 그대로, B누적은 dp[cur]+b

				int option2 = (cur >= a && dp[cur - a] != INF) ? dp[cur - a] : INF;
				// [A에게 배정] 이전 A누적은 (cur-a)였어야 함, B누적은 dp[cur-a] 그대로
				// (cur<a면 인덱스 음수라 불가능 → INF, 이전 상태 자체가 INF여도 불가능)

				dp[cur] = Math.min(option1, option2); // 두 선택 중 B누적이 더 작은(유리한) 쪽 채택
			}
		}

		for(int a= 0; a < n; a++ ) {   // A누적 후보를 0부터 오름차순으로 검사
			if(dp[a] < m)return a;     // B누적(dp[a])이 m 미만인 첫 후보가 곧 A흔적 최솟값 정답
		}
		return -1; // 끝까지 조건 만족하는 값이 없으면 둘 다 안 잡히는 배정이 불가능
	}
}
