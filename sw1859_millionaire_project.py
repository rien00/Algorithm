"""
SW Expert Academy 1859. 백만장자 프로젝트 (D2)
--------------------------------------------------
[문제 요약]
- N일간의 매매가가 주어진다.
- 하루에 최대 1개까지만 '구매'할 수 있다. (감시망 회피 조건)
- '판매'는 개수 제한이 없다.
- 목표: 최대 이익을 구하라.

[핵심 아이디어 - 그리디(Greedy)]
1. "i번째 날에 사서, i번째 날 이후 중 가장 비싼 날에 판다"가 항상 최적이다.
   → 어차피 하루에 1개만 살 수 있으므로, 각 날짜의 물건은
     "그 날짜 이후로 나타나는 최댓값"에 파는 것이 그 물건 하나에 대한 최대 이익이다.
2. 따라서 각 날짜 i에 대해 필요한 값은 "i일 이후(자기 자신 포함)의 최댓값"이다.
   이 값을 배열을 뒤에서부터 훑으면서 실시간으로 갱신하면 O(N)에 구할 수 있다.
3. 뒤에서부터 순회하면서
   - 현재 가격이 지금까지 본 최댓값(max_price)보다 크면:
     → 이 날짜가 새로운 "미래 최댓값"이 되므로 max_price를 갱신한다.
       (즉, 이 날짜 스스로가 최적의 판매 시점이 되므로 사지 않는다.)
   - 현재 가격이 max_price보다 작거나 같으면:
     → 이 날짜에 사서 max_price에 파는 것이 이득이므로
       profit += (max_price - price[i])

[복잡도]
- 시간복잡도: O(N)  (N ≤ 1,000,000 이므로 O(N log N) 이상은 시간초과 위험)
- 공간복잡도: O(N)  (가격 리스트 저장)

[주의할 함정 - 실제 채점에서 많이 틀리는 이유]
- 최대 이익 값의 상한: N(최대 1,000,000) × 가격(최대 10,000) ≈ 10^10
  → C/C++/Java에서는 int(약 21억) 범위를 초과하므로 반드시 long/long long 사용.
  → 파이썬은 정수 오버플로우가 없어 이 문제에서 자유롭다(이 스크립트 그대로 안전).
- max() 함수를 매번 구간에 대해 호출하거나(O(N) 반복 호출로 O(N^2)),
  앞에서부터 인덱스를 찾아나가는 방식은 시간초과가 발생한다.
  → 반드시 "뒤에서부터 한 번만 훑는" O(N) 방식을 사용해야 한다.
"""

import sys


def solve() -> None:
    input_stream = sys.stdin
    read_line = input_stream.readline

    T = int(read_line())  # 테스트 케이스 개수
    results = []

    for tc in range(1, T + 1):
        N = int(read_line())  # 날짜 수 (1 ≤ N ≤ 1,000,000)
        prices = list(map(int, read_line().split()))  # 일자별 매매가 리스트

        profit = 0        # 누적 최대 이익
        max_price = 0      # 현재 위치(i) '이후'의 최댓값 (초기값 0: 가격이 자연수이므로 안전한 초기값)

        # 배열을 뒤에서(마지막 날)부터 앞으로(첫째 날) 순회한다.
        # → 이렇게 해야 "i일 이후 최댓값"을 별도의 재탐색 없이 실시간으로 유지할 수 있다.
        for price in reversed(prices):
            if price > max_price:
                # 지금까지 본 것 중 가장 비싼 날 발견
                # → 이 날은 사지 않고, 앞으로 나올 더 이른 날짜들의 '판매 목표가'로 삼는다.
                max_price = price
            else:
                # 현재 가격(price)이 미래 최댓값(max_price)보다 낮다
                # → 오늘 하루치(1개)를 사서 max_price 시점에 팔면 이득이 생긴다.
                profit += max_price - price

        results.append(f"#{tc} {profit}")

    print("\n".join(results))


if __name__ == "__main__":
    solve()
