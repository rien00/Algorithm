package Study_B1.Day03;

import java.util.Arrays;

public class prog_단속 {

	/*
	 * 문제 요약
	 * 모든 차량이 적어도 한 번 카메라를 만나도록 필요한 최소 카메라 수를 구한다.
	 *
	 * 진출 지점이 빠른 차량부터 보고, 아직 단속되지 않은 차량의 진출 지점에
	 * 카메라를 설치하면 현재 차량을 놓치지 않으면서 뒤 차량과 겹칠 가능성을 최대화할 수 있다.
	 */
	public int solution(int[][] routes) {
		/*
		 * 핵심 아이디어: 가장 빨리 고속도로를 빠져나가는 차량부터 처리하는 그리디 알고리즘.
		 *
		 * 한 차량의 이동 구간은 [진입 지점, 진출 지점]이다.
		 * 아직 카메라를 만나지 못한 차량이 나오면 그 차량의 진출 지점에 카메라를 둔다.
		 * 진출 지점보다 더 뒤에 설치하면 현재 차량을 단속할 수 없고,
		 * 더 앞에 설치하면 뒤 차량들과 함께 단속할 기회를 줄일 수 있기 때문이다.
		 */
		// 1. 진출 지점(routes[i][1])이 빠른 차량부터 보도록 오름차순 정렬한다.
		Arrays.sort(routes, (a,b) -> Integer.compare(a[1], b[1]));
		
		// 마지막으로 설치한 카메라 위치. 첫 차량은 반드시 검사 대상이 되도록 최솟값으로 시작한다.
		int camera = Integer.MIN_VALUE;
		// 설치한 카메라의 개수
		int count = 0;
		
		for (int i = 0; i < routes.length; i++) {
			/*
			 * 현재 차량의 진입 지점이 마지막 카메라보다 뒤에 있다면
			 * 기존 카메라는 현재 차량의 이동 구간에 포함되지 않는다.
			 * 경계가 같은 경우에는 카메라를 만날 수 있으므로 '>'로 비교한다.
			 */
			if(routes[i][0] > camera) {
				// 현재 차량을 단속하면서 다음 차량도 최대한 함께 단속하도록 진출 지점에 설치한다.
				camera = routes[i][1];
				count++;
			}
		}
		
		// 정렬 O(N log N), 순회 O(N)이므로 전체 시간 복잡도는 O(N log N)이다.
		return count;
		
	}
}
